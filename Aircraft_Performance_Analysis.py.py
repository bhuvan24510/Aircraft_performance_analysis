def dynamic_pressure(rho, v):
    """q = 0.5 * rho * V^2  (Pa)"""
    return 0.5 * rho * (v ** 2)


def lift_force(q, s, cl):
    """L = q * S * CL  (N)"""
    return q * s * cl


def drag_force(q, s, cd):
    """D = q * S * CD  (N)"""
    return q * s * cd


def lift_to_drag(lift, drag):
    """L/D ratio (dimensionless)"""
    return lift / drag


def read_positive(prompt):
    """Read a positive floating-point number from the user."""
    while True:
        try:
            value = float(input(prompt))
            if value > 0:
                return value
            print("Value must be greater than zero. Try again.")
        except ValueError:
            print("Invalid input. Please enter a number.")


def main():
    print("=== Aircraft Performance Analysis ===")
    rho = read_positive("Air density, rho (kg/m^3) [sea level = 1.225]: ")
    v = read_positive("Velocity, V (m/s): ")
    s = read_positive("Wing area, S (m^2): ")
    cl = read_positive("Lift coefficient, CL: ")
    cd = read_positive("Drag coefficient, CD: ")

    q = dynamic_pressure(rho, v)
    lift = lift_force(q, s, cl)
    drag = drag_force(q, s, cd)
    ld = lift_to_drag(lift, drag)

    print("\n--- Results ---")
    print(f"Dynamic pressure (q) : {q:.2f} Pa")
    print(f"Lift force (L)       : {lift:.2f} N")
    print(f"Drag force (D)       : {drag:.2f} N")
    print(f"Lift-to-drag (L/D)   : {ld:.2f}")


if __name__ == "__main__":
    main()

import numpy as np
import matplotlib.pyplot as plt

rho, s, cl, cd = 1.225, 16.2, 0.6, 0.03
v = np.arange(40, 101, 10)          # m/s
q = 0.5 * rho * v ** 2
lift = q * s * cl
drag = q * s * cd

plt.plot(v, lift, marker="o", label="Lift (N)")
plt.plot(v, drag, marker="s", label="Drag (N)")
plt.xlabel("Velocity (m/s)")
plt.ylabel("Force (N)")
plt.title("Lift and Drag vs Velocity")
plt.grid(True)
plt.legend()
plt.show()